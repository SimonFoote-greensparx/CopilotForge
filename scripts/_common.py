def sections(body):
    """Return [(level, title, text)] for ## and ### headings."""
    out = []
    parts = re.split(r"^(#{2,3}) (.+)$", body, flags=re.M)
    for i in range(1, len(parts), 3):
        out.append((len(parts[i]), parts[i + 1].strip(), parts[i + 2]))
    return out


def word_count(text):
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’-]*", text))


# --- A small JSON Schema subset validator (type, required, properties, additionalProperties, enum, items, minItems,
# --- minimum, maximum, minLength, maxLength, pattern). Enough for the repository schemas without extra packages.
TYPES = {"object": dict, "array": list, "string": str, "integer": int, "number": (int, float), "boolean": bool}


def validate_schema(value, schema, where="$"):
    errs = []
    t = schema.get("type")
    if t:
        allowed = t if isinstance(t, list) else [t]
        ok = False
        for a in allowed:
            if a == "null" and value is None:
                ok = True
            elif a in TYPES and isinstance(value, TYPES[a]) and not (a in ("integer", "number") and isinstance(value, bool)):
                ok = True
        if not ok:
            return [f"{where}: expected {t}, got {type(value).__name__}"]
    if "enum" in schema and value not in schema["enum"]:
        errs.append(f"{where}: {value!r} is not one of {schema['enum']}")
    if isinstance(value, str):
        if "minLength" in schema and len(value) < schema["minLength"]:
            errs.append(f"{where}: shorter than {schema['minLength']}")
        if "maxLength" in schema and len(value) > schema["maxLength"]:
            errs.append(f"{where}: longer than {schema['maxLength']}")
        if "pattern" in schema and not re.search(schema["pattern"], value):
            errs.append(f"{where}: does not match {schema['pattern']}")
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if "minimum" in schema and value < schema["minimum"]:
            errs.append(f"{where}: below {schema['minimum']}")
        if "maximum" in schema and value > schema["maximum"]:
            errs.append(f"{where}: above {schema['maximum']}")
    if isinstance(value, dict):
        for r in schema.get("required", []):
            if r not in value:
                errs.append(f"{where}: missing required '{r}'")
        props = schema.get("properties", {})
        for k, v in value.items():
            if k in props:
                errs += validate_schema(v, props[k], f"{where}.{k}")
            elif schema.get("additionalProperties") is False:
                errs.append(f"{where}: unexpected property '{k}'")
            elif isinstance(schema.get("additionalProperties"), dict):
                errs += validate_schema(v, schema["additionalProperties"], f"{where}.{k}")
    if isinstance(value, list):
        if "minItems" in schema and len(value) < schema["minItems"]:
            errs.append(f"{where}: fewer than {schema['minItems']} items")
        if "items" in schema:
            for i, v in enumerate(value):
                errs += validate_schema(v, schema["items"], f"{where}[{i}]")
    return errs


def load_schema(name):
    with open(path("schemas", f"{name}.schema.json"), encoding="utf-8") as f:
        return json.load(f)


def check_flag():
    return "--check" in sys.argv[1:]


def write_or_check(relpath, content, check, problems):
    p = path(relpath)
    if not content.endswith("\n"):
        content += "\n"
    if check:
        cur = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if cur != content:
            problems.append(f"{relpath} is out of date; run bash scripts/build-all.sh")
        return
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def write_or_check_bytes(relpath, data, check, problems):
    p = path(relpath)
    if check:
        cur = open(p, "rb").read() if os.path.exists(p) else None
        if cur != data:
            problems.append(f"{relpath} is out of date; run bash scripts/build-all.sh")
        return
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "wb") as f:
        f.write(data)


def finish(label, problems, count, warnings=()):
    for w in warnings:
        print(f"  WARN {w}")
    for p in problems:
        print(f"  FAIL {p}")
    print(f"  {label}: {count} checked, {len(problems)} problems" + (f", {len(warnings)} warnings" if warnings else ""))
    sys.exit(1 if problems else 0)
